export type ArabicKey = keyof typeof AR;

export function t(key: ArabicKey, vars?: Record<string, string | number>): string {
  let text = AR[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}